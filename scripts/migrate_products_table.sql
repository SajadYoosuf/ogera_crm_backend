-- Product catalogue: dropdown options (brand / category / material) and products.
-- create_all makes these on startup; run this by hand only if you manage the schema yourself.
CREATE TABLE IF NOT EXISTS product_options (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    name VARCHAR(80) NOT NULL,
    slug VARCHAR(80) NOT NULL,
    is_active SMALLINT NOT NULL DEFAULT 1,
    UNIQUE KEY uq_product_options_kind_slug (kind, slug),
    INDEX ix_product_options_kind (kind)
);

CREATE TABLE IF NOT EXISTS products (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    brand_id INT NULL,
    category_id INT NULL,
    material_id INT NULL,
    tagline VARCHAR(200) NULL,
    short_description TEXT NULL,
    is_popular SMALLINT NOT NULL DEFAULT 0,
    is_active SMALLINT NOT NULL DEFAULT 1,
    model_number VARCHAR(80) NULL,
    sku VARCHAR(80) NULL UNIQUE,
    capacity_litres INT NULL,
    capacity_display VARCHAR(40) NULL,
    orientation VARCHAR(20) NULL,
    features JSON NULL,
    mrp DECIMAL(10,2) NULL,
    sale_price DECIMAL(10,2) NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    special_price_active SMALLINT NOT NULL DEFAULT 0,
    tax_included SMALLINT NOT NULL DEFAULT 1,
    height_cm DECIMAL(8,2) NULL,
    length_cm DECIMAL(8,2) NULL,
    width_cm DECIMAL(8,2) NULL,
    tank_diameter_mm DECIMAL(8,2) NULL,
    inlet_in DECIMAL(6,2) NULL,
    outlet_in DECIMAL(6,2) NULL,
    drain_in DECIMAL(6,2) NULL,
    thickness_mm DECIMAL(6,2) NULL,
    weight_kg DECIMAL(8,2) NULL,
    main_image_url VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    INDEX ix_products_name (name),
    INDEX ix_products_brand_id (brand_id),
    INDEX ix_products_category_id (category_id),
    FOREIGN KEY (brand_id) REFERENCES product_options (id),
    FOREIGN KEY (category_id) REFERENCES product_options (id),
    FOREIGN KEY (material_id) REFERENCES product_options (id)
);
